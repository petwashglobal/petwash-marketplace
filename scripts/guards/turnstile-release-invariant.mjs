#!/usr/bin/env node
/**
 * Release invariant: Turnstile's two halves must ship together.
 *
 * WHY THIS EXISTS. On 2026-09-06 production had NEITHER half:
 *
 *   TURNSTILE_SECRET_KEY      absent from Cloud Run and Secret Manager
 *   VITE_TURNSTILE_SITE_KEY   absent from the GitHub Actions secrets, so the
 *                             build substituted "" and Vite dead-code-eliminated
 *                             the widget out of the bundle entirely
 *
 * turnstileGuard fails CLOSED in production, so POST /api/auth/email/start and
 * POST /api/auth/sms/start were returning 503 to every customer. Nobody could
 * sign up or sign in by code. It had been that way since the Replit -> Cloud
 * Run migration, and nothing in the pipeline noticed — the only signal was a
 * /health endpoint that described the surfaces as merely "unprotected".
 *
 * A release must now fail BEFORE traffic moves, not after customers are locked
 * out. This checks both halves and, crucially, checks the BUILT BUNDLE rather
 * than trusting that an env var reached the compiler.
 *
 * WHAT THIS PROVES, precisely. The two halves are proven by two INDEPENDENT
 * mechanisms — there is no shared detector across them, and describing it that
 * way earlier was wrong:
 *
 *   client half  the BUILT ARTIFACT is scanned (shared with the build-config
 *                writer, so the gate and /api/health/bot-check agree)
 *   server half  the CANDIDATE DEPLOYMENT's secret bindings are inspected —
 *                the arguments the next revision will actually be created
 *                with, not the configuration of the revision already running
 *
 * That distinction was the hole in the first version. Inspecting
 * `gcloud run services describe` proves the CURRENT service has a binding; it
 * says nothing about the revision about to replace it. A deploy template that
 * dropped the binding would sail past a check of the old service.
 *
 * TWO HALVES, TWO DIFFERENT STORES — and the check must respect that:
 *
 *   VITE_TURNSTILE_SITE_KEY  PUBLIC. Compiled into the browser bundle, so the
 *                            build system legitimately knows it. Verified by
 *                            inspecting the ARTIFACT.
 *   TURNSTILE_SECRET_KEY     SERVER-ONLY. Belongs in GCP Secret Manager, bound
 *                            to Cloud Run. Verified by inspecting the DEPLOY
 *                            BINDING — never by having the value.
 *
 * An earlier version read `secrets.TURNSTILE_SECRET_KEY` from GitHub Actions
 * so CI could check presence. That was wrong architecture: it pushes a
 * server-only production secret into a second secret store purely to satisfy
 * a check, widening exposure for no benefit. GitHub does not need the value
 * and no longer receives it.
 *
 * It never prints, logs or compares key values — only presence and bindings.
 *
 *   node scripts/guards/turnstile-release-invariant.mjs [--dist dist/public]
 *                                                       [--service petwash-api]
 *                                                       [--region me-west1]
 *                                                       [--project signinpetwash]
 *
 * Exit 0 = both halves present (or non-production, where it warns only).
 * Exit 1 = a production release that would strand signup.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { detectTurnstileInBundle } from './turnstileBundleDetect.mjs';

const args = process.argv.slice(2);
const distArg = args.indexOf('--dist');
const DIST = distArg !== -1 ? args[distArg + 1] : 'dist/public';

// A release is "production" when the pipeline says so. Default to strict:
// a guard that silently opts out is the failure mode it exists to prevent.
const IS_PRODUCTION =
  process.env.TURNSTILE_INVARIANT_ENV === 'production'
  || process.env.NODE_ENV === 'production'
  || process.env.GITHUB_REF === 'refs/heads/main';

const problems = [];
const notes = [];

// ── half 1: the server secret, checked on the CANDIDATE DEPLOYMENT ─────────
//
// The question is "will the revision we are ABOUT TO CREATE receive
// TURNSTILE_SECRET_KEY?". The pipeline answers it directly: the deploy step is
// given `secrets: <secret_mappings>`, generated by the build-cloudrun-secrets
// step from required_mappings. Validating that string validates the actual
// deploy argument.
//
// FAILS CLOSED. If the candidate mapping cannot be read on a production
// release, the release is BLOCKED. A gate that cannot evaluate must not wave
// the release through and defer to a post-deploy health check — that is how a
// guard becomes decoration. Post-deploy health remains a SECOND, independent
// gate, not a substitute for this one.
function checkServerHalf() {
  /**
   * The pipeline gates the two halves at two different moments, because they
   * become knowable at different moments: the client half as soon as the
   * bundle exists, the server half only once the candidate secret mappings
   * are generated. This opt-out is for the EARLY, client-only pass — it is
   * not a way to skip the server half of a release, which is gated
   * separately and unconditionally later.
   */
  if (process.env.TURNSTILE_SKIP_SERVER_HALF === 'client-half-only') {
    notes.push('Server half deferred to the candidate-mappings gate later in this release.');
    return;
  }

  const mapArg = args.indexOf('--secret-mappings');
  const inline = mapArg !== -1 ? args[mapArg + 1] : undefined;
  const fromEnv = process.env.CLOUDRUN_SECRET_MAPPINGS;
  const candidate = inline ?? fromEnv;

  if (typeof candidate === 'string' && candidate.trim().length > 0) {
    // Mappings are `ENV_NAME=SECRET_NAME:version`, newline or comma separated.
    const bound = candidate
      .split(/[\n,]+/)
      .map((m) => m.trim())
      .filter(Boolean)
      .some((m) => m.split('=')[0] === 'TURNSTILE_SECRET_KEY');

    if (bound) {
      notes.push('Candidate deployment binds TURNSTILE_SECRET_KEY from Secret Manager (value not read).');
    } else {
      problems.push(
        'The CANDIDATE deployment does not bind TURNSTILE_SECRET_KEY. turnstileGuard fails '
        + 'CLOSED in production, so the new revision would return 503 on '
        + '/api/auth/email/start and /api/auth/sms/start. Add '
        + '"TURNSTILE_SECRET_KEY=TURNSTILE_SECRET_KEY:latest" to required_mappings in '
        + 'petwash-ci.yml — do NOT copy the value into GitHub Actions.',
      );
    }
    return;
  }

  // No candidate mapping available. Fall back to describing the CURRENT
  // service — useful as a diagnostic, never sufficient as the invariant.
  let currentBound = null;
  try {
    const svcArg = args.indexOf('--service');
    const regArg = args.indexOf('--region');
    const projArg = args.indexOf('--project');
    const service = svcArg !== -1 ? args[svcArg + 1] : (process.env.CLOUD_RUN_SERVICE || 'petwash-api');
    const region = regArg !== -1 ? args[regArg + 1] : (process.env.CLOUD_RUN_REGION || 'me-west1');
    const project = projArg !== -1 ? args[projArg + 1] : (process.env.GCP_PROJECT || 'signinpetwash');
    const out = execFileSync('gcloud', [
      'run', 'services', 'describe', service,
      '--region', region, '--project', project,
      '--format', 'json(spec.template.spec.containers[0].env)',
    ], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], timeout: 60_000 });
    const env = JSON.parse(out)?.spec?.template?.spec?.containers?.[0]?.env ?? [];
    currentBound = env.some((e) => e?.name === 'TURNSTILE_SECRET_KEY'
      && (e?.valueFrom?.secretKeyRef?.name || typeof e?.value === 'string'));
  } catch {
    currentBound = null; // unknown — gcloud missing, unauthenticated, or malformed
  }

  if (currentBound === true) {
    notes.push(
      'Currently deployed service binds TURNSTILE_SECRET_KEY (diagnostic only — this does '
      + 'NOT prove the candidate revision will).',
    );
  }

  problems.push(
    'Could not verify the CANDIDATE deployment binds TURNSTILE_SECRET_KEY: no secret '
    + 'mappings were supplied (--secret-mappings / CLOUDRUN_SECRET_MAPPINGS)'
    + (currentBound === true
      ? ', and the currently deployed service is not evidence about the next revision.'
      : currentBound === false
        ? ', and the currently deployed service does not bind it either.'
        : ', and the current service could not be queried.')
    + ' A release gate that cannot evaluate must BLOCK, not defer to post-deploy health.',
  );
}
checkServerHalf();

// ── half 2: the site key, as actually COMPILED into the bundle ──────────────
//
// Checking process.env.VITE_TURNSTILE_SITE_KEY here would prove nothing about
// the artifact being shipped: the value is inlined at build time, so a var set
// after the build, or in a different job, is invisible to the browser. The
// only honest check is the bundle itself.
//
// The detector is shared with the build-config writer — but ONLY for this,
// the client half. The server half is proven independently, from the candidate
// deployment's secret bindings. Saying "one shared detector backs both halves"
// was wrong; they are two independent mechanisms, and that separation is the
// point: a single detector could not tell you both what the browser received
// and what the container will receive.
const t = detectTurnstileInBundle(DIST);

if (!t.artifactFound) {
  problems.push(
    `No built JS found under ${DIST}. Run this AFTER the client build, or pass `
    + '--dist <path>; a release cannot be validated against an artifact that '
    + 'does not exist.',
  );
} else if (!t.widgetPresent) {
  notes.push(`No Turnstile widget code found in ${DIST} (nothing to validate).`);
} else if (!t.turnstileConfigured) {
  problems.push(
    'The client bundle was built WITHOUT VITE_TURNSTILE_SITE_KEY: the widget '
    + 'render path was dead-code-eliminated and executeTurnstileInvisible() '
    + 'can only return SITE_KEY_MISSING. The browser will never obtain a '
    + 'token, so signup stays dead even if the server secret is bound. '
    + 'A VITE_* value is compiled in — set it in the BUILD environment and '
    + 'rebuild the client; adding it to Cloud Run afterwards changes nothing. '
    + 'The site key is PUBLIC, so a GitHub variable is an appropriate home.',
  );
} else {
  notes.push('Client bundle carries a Turnstile site key (value not read).');
}

// ── the artifact must also carry its own build metadata ─────────────────────
//
// /api/health/bot-check reports the client half from build-config.json and
// treats a missing file as UNKNOWN rather than healthy — correct, but a
// production release should never knowingly finish in that state.
if (t.artifactFound) {
  const cfgPath = join(DIST, 'build-config.json');
  if (!existsSync(cfgPath)) {
    problems.push(
      `${cfgPath} is missing. The deployed server would report the client half as UNKNOWN. `
      + 'Run scripts/guards/write-build-config.mjs after the client build.',
    );
  } else {
    try {
      const parsed = JSON.parse(readFileSync(cfgPath, 'utf8'));
      if (typeof parsed?.turnstileConfigured !== 'boolean') {
        problems.push(`${cfgPath} is malformed (turnstileConfigured is not a boolean).`);
      } else if (parsed.turnstileConfigured !== t.turnstileConfigured) {
        // The writer and this gate share one detector, so a mismatch means the
        // metadata is stale relative to the artifact being shipped.
        problems.push(
          `${cfgPath} disagrees with the artifact (metadata says `
          + `turnstileConfigured=${parsed.turnstileConfigured}, the bundle says `
          + `${t.turnstileConfigured}). Regenerate it against THIS build.`,
        );
      } else {
        notes.push('Client build metadata present and consistent with the artifact.');
      }
    } catch {
      problems.push(`${cfgPath} is not valid JSON.`);
    }
  }
}

for (const n of notes) console.log(`  ok   ${n}`);
for (const p of problems) console.error(`  FAIL ${p}`);

if (problems.length === 0) {
  console.log('Turnstile release invariant: OK — both halves ship together.');
  process.exit(0);
}

if (!IS_PRODUCTION) {
  console.warn(
    '\nNon-production release — not blocking. The SAME configuration would '
    + 'take signup and sign-in DOWN in production.',
  );
  process.exit(0);
}

console.error(
  '\nRelease BLOCKED. Both halves of Turnstile must be provisioned together:\n'
  + '  TURNSTILE_SECRET_KEY     -> server runtime (Cloud Run / Secret Manager)\n'
  + '  VITE_TURNSTILE_SITE_KEY  -> client BUILD environment, then rebuild\n'
  + 'Both must come from the same Cloudflare Turnstile widget for petwash.co.il.\n'
  + 'The site key is public by design; the secret key is server-only.',
);
process.exit(1);
